import unittest
from pathlib import Path

import pandas as pd


class SectorCoverageMatrixTests(unittest.TestCase):
    def test_local_and_global_sector_scopes_are_distinguished(self):
        path = Path(__file__).resolve().parents[1] / "data" / "sector_coverage_matrix.csv"
        matrix = pd.read_csv(path, dtype=str).fillna("").set_index("country_or_region")
        self.assertEqual(matrix.loc["United States", "local_sector_coverage_status"], "local_sector_etfs_in_universe")
        self.assertEqual(matrix.loc["South Korea", "local_sector_coverage_status"], "partial_local_sector_coverage")
        self.assertEqual(matrix.loc["Japan", "local_sector_coverage_status"], "partial_local_sector_coverage")
        self.assertEqual(matrix.loc["Global", "local_sector_coverage_status"], "global_sector_etfs_in_universe")
        self.assertEqual(matrix.loc["Japan", "fallback_scope"], "Global")
        self.assertEqual(matrix.loc["Japan", "workstream_priority"], "core")
        self.assertEqual(matrix.loc["India", "local_sector_coverage_status"], "partial_us_listed_country_sector_proxy")
        self.assertEqual(matrix.loc["India", "us_listed_country_sector_proxy_symbols"], "INCO")
        self.assertEqual(matrix.loc["China", "local_sector_coverage_status"], "partial_us_listed_country_sector_proxy")
        self.assertEqual(matrix.loc["China", "us_listed_country_sector_proxy_symbols"], "KWEB;CQQQ;CHIQ;CHIE;CHIX;CHII;CHIM;CHIC")
        self.assertTrue(matrix["market_proxy_symbol"].ne("").all())
        self.assertTrue(matrix["notes"].ne("").all())
        universe_path = Path(__file__).resolve().parents[1] / "data" / "monitoring_universe.csv"
        universe = pd.read_csv(universe_path, dtype={"symbol": str}).set_index("symbol")
        self.assertEqual(universe.loc["INCO", "asset_type"], "sector_etf")
        self.assertEqual(universe.loc["INCO", "market"], "India")
        self.assertEqual(universe.loc["INCO", "market_benchmark"], "INDA")
        self.assertEqual(universe.loc["KWEB", "market"], "China")
        self.assertEqual(universe.loc["KWEB", "market_benchmark"], "MCHI")
        self.assertEqual(universe.loc["CQQQ", "market"], "China")
        self.assertEqual(universe.loc["CQQQ", "market_benchmark"], "MCHI")
        self.assertEqual(universe.loc["CHIQ", "asset_type"], "sector_etf")
        self.assertEqual(universe.loc["CHIQ", "market"], "China")
        self.assertEqual(universe.loc["CHIQ", "market_benchmark"], "MCHI")
        self.assertEqual(universe.loc["CHIE", "asset_type"], "sector_etf")
        self.assertEqual(universe.loc["CHIE", "market"], "China")
        self.assertEqual(universe.loc["CHIE", "market_benchmark"], "MCHI")
        self.assertEqual(universe.loc["CHIX", "asset_type"], "sector_etf")
        self.assertEqual(universe.loc["CHIX", "market"], "China")
        self.assertEqual(universe.loc["CHIX", "market_benchmark"], "MCHI")
        self.assertEqual(universe.loc["CHII", "asset_type"], "sector_etf")
        self.assertEqual(universe.loc["CHII", "market"], "China")
        self.assertEqual(universe.loc["CHII", "market_benchmark"], "MCHI")
        self.assertEqual(universe.loc["CHIM", "asset_type"], "sector_etf")
        self.assertEqual(universe.loc["CHIM", "market"], "China")
        self.assertEqual(universe.loc["CHIM", "market_benchmark"], "MCHI")
        self.assertEqual(universe.loc["CHIC", "asset_type"], "sector_etf")
        self.assertEqual(universe.loc["CHIC", "market"], "China")
        self.assertEqual(universe.loc["CHIC", "market_benchmark"], "MCHI")
        self.assertEqual(universe.loc["213A", "exchange"], "TSE")
        self.assertEqual(universe.loc["2644", "exchange"], "TSE")
        self.assertEqual(universe.loc["1615", "exchange"], "TSE")
        self.assertEqual(universe.loc["1615", "market"], "Japan")
        self.assertEqual(universe.loc["1617", "exchange"], "TSE")
        self.assertEqual(universe.loc["1617", "market"], "Japan")
        self.assertEqual(universe.loc["1618", "exchange"], "TSE")
        self.assertEqual(universe.loc["1618", "market"], "Japan")
        self.assertEqual(universe.loc["1629", "exchange"], "TSE")
        self.assertEqual(universe.loc["1629", "market"], "Japan")
        self.assertEqual(universe.loc["1630", "exchange"], "TSE")
        self.assertEqual(universe.loc["1630", "market"], "Japan")
        self.assertEqual(universe.loc["1631", "exchange"], "TSE")
        self.assertEqual(universe.loc["1631", "market"], "Japan")
        self.assertEqual(universe.loc["1632", "exchange"], "TSE")
        self.assertEqual(universe.loc["1632", "market"], "Japan")
        self.assertEqual(universe.loc["1633", "exchange"], "TSE")
        self.assertEqual(universe.loc["1633", "market"], "Japan")


